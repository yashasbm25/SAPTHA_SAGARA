
import { useEffect } from "react";
import {
  MapContainer,
  TileLayer,
  Marker,
  Popup,
  Polyline,
  CircleMarker,
  useMap,
} from "react-leaflet";
import L from "leaflet";
import "leaflet/dist/leaflet.css";
import "./MarineMap.css";

const DEFAULT_POINTS = {
  Mangalore: [12.8698247, 74.8430125],
  Mangaluru: [12.8698247, 74.8430125],
  Goa: [15.3004543, 74.0855134],
  Panaji: [15.4909, 73.8278],
  Karwar: [14.8137, 74.1297],
  Udupi: [13.3409, 74.7421],
  Kochi: [9.9312, 76.2673],
  Mumbai: [19.076, 72.8777],
  Chennai: [13.0827, 80.2707],
  Visakhapatnam: [17.6868, 83.2185],
};

function createIcon(color) {
  return L.divIcon({
    className: "marine-map-marker",
    html: `<div style="
      width: 14px;
      height: 14px;
      background: ${color};
      border: 2px solid white;
      border-radius: 50%;
      box-shadow: 0 0 8px rgba(0,0,0,0.45);
    "></div>`,
    iconSize: [18, 18],
    iconAnchor: [9, 9],
  });
}

const originIcon = createIcon("#16a878");
const destinationIcon = createIcon("#ef8354");

function formatValue(value, suffix = "") {
  if (value === null || value === undefined || value === "") {
    return "Unavailable";
  }

  const number = Number(value);

  if (!Number.isFinite(number)) {
    return "Unavailable";
  }

  return `${number.toLocaleString("en-IN", {
    maximumFractionDigits: 2,
  })}${suffix}`;
}

function MapBounds({ points }) {
  const map = useMap();

  useEffect(() => {
    if (!points.length) return;

    const bounds = L.latLngBounds(points);

    if (bounds.isValid()) {
      map.fitBounds(bounds, {
        padding: [35, 35],
        maxZoom: 8,
      });
    }
  }, [map, points]);

  return null;
}

export default function MarineMap({
  origin = "Mangalore",
  destination = "Goa",
  routeData = null,
}) {
  const originPoint =
    routeData?.origin?.latitude != null &&
    routeData?.origin?.longitude != null
      ? [
          Number(routeData.origin.latitude),
          Number(routeData.origin.longitude),
        ]
      : DEFAULT_POINTS[origin] || DEFAULT_POINTS.Mangalore;

  const destinationPoint =
    routeData?.destination?.latitude != null &&
    routeData?.destination?.longitude != null
      ? [
          Number(routeData.destination.latitude),
          Number(routeData.destination.longitude),
        ]
      : DEFAULT_POINTS[destination] || DEFAULT_POINTS.Goa;

  const waypointPoints = Array.isArray(routeData?.waypoints)
    ? routeData.waypoints
        .filter(
          (point) =>
            Number.isFinite(Number(point.latitude)) &&
            Number.isFinite(Number(point.longitude)),
        )
        .map((point) => [
          Number(point.latitude),
          Number(point.longitude),
        ])
    : [];

  const displayedRoute =
    waypointPoints.length > 1
      ? waypointPoints
      : routeData
        ? [originPoint, destinationPoint]
        : [];

  const mapPoints =
    displayedRoute.length > 1
      ? displayedRoute
      : [originPoint, destinationPoint];

  return (
    <div className="marine-map-panel">
      <div className="marine-map-heading">
        <div>
          <p className="marine-map-eyebrow">MARINE ROUTE VISUALIZATION</p>
          <h2>Marine operations map</h2>
          <p className="marine-map-subtitle">
            View the route generated by the existing route planner.
          </p>
        </div>

        <div className="marine-map-live-tag">
          <span className="marine-map-live-dot" />
          Route visualization
        </div>
      </div>

      <div className="marine-map-canvas">
        <MapContainer
          center={[13.8, 74.5]}
          zoom={6}
          scrollWheelZoom={true}
          className="marine-leaflet-map"
          style={{ height: "100%", width: "100%" }}
        >
          <TileLayer
            attribution="&copy; OpenStreetMap contributors"
            url="https://{s}.tile.openstreetmap.fr/osmfr/{z}/{x}/{y}.png"
          />

          <MapBounds points={mapPoints} />

          <Marker position={originPoint} icon={originIcon}>
            <Popup>
              <strong>Origin</strong>
              <br />
              {routeData?.origin?.name || origin}
            </Popup>
          </Marker>

          <Marker position={destinationPoint} icon={destinationIcon}>
            <Popup>
              <strong>Destination</strong>
              <br />
              {routeData?.destination?.name || destination}
            </Popup>
          </Marker>

          {displayedRoute.length > 1 && (
            <Polyline
              positions={displayedRoute}
              pathOptions={{
                color: "#168bd2",
                weight: 4,
                opacity: 0.9,
              }}
            />
          )}

          {waypointPoints.map((point, index) => (
            <CircleMarker
              key={`${point[0]}-${point[1]}-${index}`}
              center={point}
              radius={4}
              pathOptions={{
                color: "#ffffff",
                weight: 1,
                fillColor: "#168bd2",
                fillOpacity: 1,
              }}
            >
              <Popup>
                <strong>Waypoint {index + 1}</strong>
                <br />
                Latitude: {point[0].toFixed(5)}
                <br />
                Longitude: {point[1].toFixed(5)}
              </Popup>
            </CircleMarker>
          ))}
        </MapContainer>
      </div>

      {routeData && (
        <div className="marine-route-result">
          <div>
            <span>Estimated sea-route distance</span>
            <strong>
              {formatValue(routeData.route_distance_km, " km")}
            </strong>
          </div>

          <div>
            <span>Straight-line distance</span>
            <strong>
              {formatValue(routeData.straight_line_distance_km, " km")}
            </strong>
          </div>

          <div>
            <span>Waypoints</span>
            <strong>{waypointPoints.length}</strong>
          </div>
        </div>
      )}

      <div className="marine-map-legend">
        <span>
          <i className="legend-origin" />
          Origin
        </span>
        <span>
          <i className="legend-destination" />
          Destination
        </span>
        <span>
          <i className="legend-waypoint" />
          Route waypoints
        </span>
      </div>

      <div className="marine-map-safety-note">
        <strong>Navigation limitation</strong>
        <p>
          This route is a visualization estimate, not a certified
          navigational route. It has not been verified against official
          nautical charts, coastlines, bathymetry, vessel draft, shipping
          restrictions, currents, weather, or official marine warnings.
          Do not use it for operational navigation.
        </p>
      </div>
    </div>
  );
}
